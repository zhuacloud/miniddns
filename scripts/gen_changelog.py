#!/usr/bin/env python3
"""Validate a release version and generate the changelog entry / release notes.

All generated text is English, per CONTRIBUTING.md (all GitHub interactions
must be in English). Historical CHANGELOG.md sections keep their original
language; only sections below the marker are generated by this script.
"""
import argparse
import datetime
import os
import re
import subprocess
import sys

MARKER = "<!-- generated-release-sections -->"
VERSION_RE = re.compile(r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(-rc[1-9]\d*)?$")
DEV_VERSION = "0.0.0-dev"  # local build, never releasable

GROUPS = [
    ("Added", ("feat",)),
    ("Fixed", ("fix",)),
    ("Performance", ("perf",)),
    ("Documentation", ("docs",)),
    ("Internal", ("refactor", "test", "build", "ci", "chore", "style")),
    ("Changed", ()),  # fallback
]


def is_valid_version(value):
    return bool(VERSION_RE.match(value or ""))


def is_prerelease(value):
    return bool(re.search(r"-rc[1-9]\d*$", value or ""))


def git(*args):
    return subprocess.check_output(["git"] + list(args), text=True).strip()


def git_ok(*args):
    return subprocess.run(["git"] + list(args), stdout=subprocess.DEVNULL,
                          stderr=subprocess.DEVNULL).returncode == 0


def resolve_upto(version, requested):
    if requested:
        return requested
    if git_ok("rev-parse", "-q", "--verify", "refs/tags/" + version):
        return version
    return "HEAD"


def previous_tag(version, upto):
    tags = git("tag", "--merged", upto, "--sort=-version:refname").splitlines()
    for tag in tags:
        if tag and tag != version:
            return tag
    return None


def collect_commits(prev, upto):
    revision = "%s..%s" % (prev, upto) if prev else upto
    out = git("log", "--no-merges", "--pretty=format:%h%x09%s", revision)
    entries = []
    for line in out.splitlines():
        if "\t" not in line:
            continue
        sha, subject = line.split("\t", 1)
        entries.append((sha.strip(), subject.strip()))
    return entries


def group_commits(entries):
    buckets = {name: [] for name, _ in GROUPS}
    for sha, subject in entries:
        m = re.match(r"^([a-z]+)(?:\([^)]*\))?!?:\s*(.+)$", subject)
        kind = m.group(1) if m else ""
        placed = False
        for name, kinds in GROUPS:
            if kind in kinds:
                buckets[name].append((sha, subject))
                placed = True
                break
        if not placed:
            buckets["Changed"].append((sha, subject))
    return buckets


def section_text(version, date, buckets, notes_link, repo):
    lines = ["## [%s] - %s" % (version, date), ""]
    if notes_link:
        lines.append("**Full Changelog**: https://github.com/%s/compare/%s" % (repo, notes_link))
        lines.append("")
    any_entry = False
    for name, _ in GROUPS:
        items = buckets.get(name) or []
        if not items:
            continue
        any_entry = True
        lines.append("### %s" % name)
        lines.append("")
        for sha, subject in items:
            lines.append("- %s (%s)" % (subject, sha))
        lines.append("")
    if not any_entry:
        lines.append("_No user-facing changes since the previous tag._")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def notes_text(version, date, buckets, notes_link, repo, release_type):
    lines = [
        "# miniddns %s" % version,
        "",
        "Release date: %s" % date,
        "Release type: %s" % release_type,
        "",
    ]
    for name, _ in GROUPS:
        items = buckets.get(name) or []
        if not items:
            continue
        lines.append("## %s" % name)
        lines.append("")
        for sha, subject in items:
            lines.append("- %s (%s)" % (subject, sha))
        lines.append("")
    if notes_link:
        lines.append("**Full Changelog**: https://github.com/%s/compare/%s" % (repo, notes_link))
    else:
        lines.append("**Commits**: https://github.com/%s/commits/%s" % (repo, version))
    lines += [
        "",
        "## Artifacts",
        "",
        "- `miniddns-%s-<arch>-musl.tar.gz` — static binary, configuration example, "
        "install script, systemd/OpenWrt service configuration examples, CA snapshot, "
        "documentation and license notices." % version,
        "- `miniddns-%s-src.tar.gz` — deterministic source tarball for the "
        "OpenWrt `PKG_SOURCE` recipe." % version,
        "- `SHA256SUMS` — sha256 for every uploaded tarball.",
        "",
    ]
    return "\n".join(lines)


def update_changelog(path, version, section):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if MARKER not in text:
        raise SystemExit("ERROR: CHANGELOG.md is missing the insertion marker: %s" % MARKER)

    # Remove a previously generated section for the same version (idempotent re-run).
    lines = text.splitlines(keepends=True)
    kept = []
    skipping = False
    heading = "## [%s]" % version
    for line in lines:
        if skipping:
            if line.startswith("## [") or line.strip() == "---":
                skipping = False
                kept.append(line)
            continue
        if line.startswith(heading):
            skipping = True
            continue
        kept.append(line)
    text = "".join(kept)

    marker_line = MARKER + "\n"
    if marker_line not in text:
        text = text.replace(MARKER, marker_line)
    text = text.replace(marker_line, marker_line + "\n" + section + "\n", 1)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser(description="Validate a release version and generate changelog notes")
    ap.add_argument("--version", required=True, help="X.Y.Z or X.Y.Z-rcN")
    ap.add_argument("--validate-only", action="store_true", help="only validate the version")
    ap.add_argument("--changelog", default="CHANGELOG.md")
    ap.add_argument("--notes", default="release-assets/RELEASE_NOTES.md")
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "zhuacloud/miniddns"))
    ap.add_argument("--upto", default=None, help="git ref to generate notes up to (default: tag or HEAD)")
    ap.add_argument("--date", default=datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d"))
    args = ap.parse_args()

    version = args.version.strip()
    if version == DEV_VERSION:
        print("ERROR: %s is the local development build and cannot be released. "
              "Pass an explicit VERSION=X.Y.Z or VERSION=X.Y.Z-rcN." % DEV_VERSION,
              file=sys.stderr)
        return 3
    if not is_valid_version(version):
        print("ERROR: invalid version %r; expected X.Y.Z or X.Y.Z-rcN" % version, file=sys.stderr)
        return 2
    if args.validate_only:
        print("OK: %s (%s)" % (version, "release candidate" if is_prerelease(version) else "stable"))
        return 0

    upto = resolve_upto(version, args.upto)
    prev = previous_tag(version, upto)
    entries = collect_commits(prev, upto)
    buckets = group_commits(entries)
    link = "%s...%s" % (prev, version) if prev else None
    release_type = "release candidate (prerelease)" if is_prerelease(version) else "stable"

    section = section_text(version, args.date, buckets, link, args.repo)
    update_changelog(args.changelog, version, section)

    notes = notes_text(version, args.date, buckets, link, args.repo, release_type)
    os.makedirs(os.path.dirname(args.notes) or ".", exist_ok=True)
    with open(args.notes, "w", encoding="utf-8") as f:
        f.write(notes)

    print("Version:     %s" % version)
    print("Type:        %s" % release_type)
    print("Compared to: %s" % (prev or "(initial release)"))
    print("Commits:     %d" % len(entries))
    print("Updated:     %s" % args.changelog)
    print("Notes:       %s" % args.notes)
    return 0


if __name__ == "__main__":
    sys.exit(main())
